export function customSite(lat, lon) {
  const rough = Math.abs(lat) > 70 ? 1 : 0.5;
  lon = ((lon + 540) % 360) - 180;
  return { id: 'custom', name: `${Math.abs(lat).toFixed(2)}°${lat < 0 ? 'S' : 'N'} ${Math.abs(lon).toFixed(2)}°${lon < 0 ? 'W' : 'E'}`, cat: 'custom', lat, lon, rough };
}
